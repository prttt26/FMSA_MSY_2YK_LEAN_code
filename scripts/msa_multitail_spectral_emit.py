#!/usr/bin/env python3
"""Emit three small kernel-provable, tail-count-independent spectral identities.

These are algebra certificates for the explicit sine-transform dictionary.
The finite-tail actual-integral/Fourier bridge is a separate Lean obligation.
SymPy proposes the circle multiple; Lean proves it using field_simp and ring.
"""
from pathlib import Path
import hashlib
import json
import sympy as sp

z, w, k, si, co, ez, ew, aa, qq, ww, cc, vv, dd = sp.symbols(
    'z w k si co ez ew aa qq ww cc vv dd')
variables = (z, w, k, si, co, ez, ew, aa, qq, ww, cc, vv, dd)
psi0 = (1-co)/k
psi1 = (si-k*co)/k**2
psi2 = (-k**2*co+2*k*si+2*(co-1))/k**3
psi4 = (-k**4*co+4*k**3*si+12*k**2*co-24*k*si+24*(1-co))/k**5
pre = qq * (co-1)/k**2 + aa*(k-si)/k**3
pim = qq * (k-si)/k**2 + aa*(1-co-k**2/2)/k**3


def tail_re(z, W, C):
    return W*z/(z*z+k*k)+C*(si/k+(z*co-k*si)/(z*z+k*k))


def tail_im(z, W, C):
    return -W*k/(z*z+k*k)-C*((1-co)/k+(k*co+z*si)/(z*z+k*k))


def minus_core(z, e):
    return (k-e*(z*si+k*co))/(z*z+k*k)


def plus_core(z, e):
    return (k+(z*si-k*co)/e)/(z*z+k*k)


def outside(z, e):
    return e*(z*si+k*co)/(z*z+k*k)


pp = (-aa**2/8+aa*qq/2-qq**2/2)*psi0 + (aa**2/6-aa*qq/2)*psi1 + qq**2/2*psi2-aa**2/24*psi4
lp = qq*(1-z-ez)/z**2+aa*(1-z+z*z/2-ez)/z**3
mixed = (ww*((qq-aa)/z+aa/z**2)+cc*(qq-aa/2-qq/z-aa/z**2))*psi0 + \
    (ww*aa/z+cc*aa*(1+1/z))*psi1-cc*aa*psi2 + \
    (-z*ww*lp+cc*(qq/z+aa/z**2))*minus_core(z,ez) - \
    ww*ez*(qq/z+aa/z**2)*plus_core(z,ez) - z*(ww+cc/ez)*lp*outside(z,ez)
pair = -cc*dd*psi0 + (-z*ww*vv/(z+w)-(1-w*ez/(z+w))*ww*dd+w*cc*dd/(z+w))*minus_core(z,ez) - \
    z*cc*vv*ew/(z+w)*plus_core(w,ew) - \
    z*(ww+cc/ez)*(vv/(z+w)+dd*((1-ez)/z+ez/(z+w)))*outside(z,ez)
swap = {z:w, w:z, ez:ew, ew:ez, ww:vv, vv:ww, cc:dd, dd:cc}
pair_swapped = pair.xreplace(swap)


def lean(x):
    if x.is_Symbol:
        return str(x)
    if x.is_Integer:
        return f'({x} : ℝ)'
    if x.is_Rational:
        return f'({x.p} / {x.q} : ℝ)'
    if x.is_Add:
        return '(' + ' + '.join(lean(v) for v in x.args) + ')'
    if x.is_Mul:
        return '(' + ' * '.join(lean(v) for v in x.args) + ')'
    if x.is_Pow and x.exp.is_Integer:
        base, exponent = lean(x.base), int(x.exp)
        return f'(1 / ({base} ^ {-exponent}))' if exponent < 0 else f'({base} ^ {exponent})'
    raise TypeError(x)


def main():
    certs = (
        ('polynomialPair', pp, k/2*(pre**2+pim**2)),
        ('polynomialTail', mixed, k*(pre*tail_re(z,ww,cc)+pim*tail_im(z,ww,cc))),
        ('tailPair', pair+pair_swapped, k*(tail_re(z,ww,cc)*tail_re(w,vv,dd)+tail_im(z,ww,cc)*tail_im(w,vv,dd))),
    )
    out = ['import Mathlib', '', '/-! Generated by scripts/msa_multitail_spectral_emit.py.\n'
           'Pure algebra only: actual Fourier/convolution identification is kept separate.\n'
           'The three identities retain symbolic rates, including equal positive rates. -/',
           'noncomputable section', 'namespace FMSA.ExactMSA.MultiTail.SpectralAlgebra', '']
    meta = []
    for name, j, norm in certs:
        numerator, denominator = sp.fraction(sp.cancel(j+norm))
        quotient, remainder = sp.div(numerator, si**2+co**2-1, si)
        assert sp.expand(remainder) == 0, (name, remainder)
        quotient = sp.factor(quotient/denominator)
        args = ' '.join(str(x) for x in variables if x in j.free_symbols | norm.free_symbols)
        hypotheses = ['(hk : k ≠ 0)']
        if z in j.free_symbols:
            hypotheses.extend(['(hz : z ≠ 0)', '(hzk : z ^ 2 + k ^ 2 ≠ 0)', '(hez : ez ≠ 0)'])
        if w in j.free_symbols:
            hypotheses.extend(['(hw : w ≠ 0)', '(hzw : z + w ≠ 0)',
                               '(hwk : w ^ 2 + k ^ 2 ≠ 0)', '(hew : ew ≠ 0)'])
        hyp_names = [s.split()[0][1:] for s in hypotheses]
        if w in j.free_symbols:
            hyp_names.append('hwz')
        out.extend([
            f'def {name}Integral ({args} : ℝ) : ℝ := {lean(j)}',
            f'def {name}Product ({args} : ℝ) : ℝ := {lean(norm)}',
            '',
            f'theorem {name}_identity ({args} : ℝ)',
            '    '+' '.join(hypotheses)+' (hcircle : si ^ 2 + co ^ 2 = 1) :',
            f'    {name}Integral {args} + {name}Product {args} = 0 := by',
            f'  have hr : {name}Integral {args} + {name}Product {args} =',
            f'      {lean(quotient)} * (si ^ 2 + co ^ 2 - 1) := by',
            *(['    have hwz : w + z ≠ 0 := by simpa [add_comm] using hzw'] if w in j.free_symbols else []),
            f'    unfold {name}Integral {name}Product',
            '    field_simp ['+', '.join(hyp_names)+']',
            '    ring',
            '  rw [hcircle, sub_self, mul_zero] at hr',
            '  exact hr', '',
        ])
        meta.append(dict(name=name, circle_quotient=str(quotient),
                         numerator_terms=len(sp.Add.make_args(sp.expand(numerator)))))
    out.append('end FMSA.ExactMSA.MultiTail.SpectralAlgebra\n')
    base = Path(__file__).resolve().parents[1]
    dest = base/'LeanCode/YukawaOZ/MSAMultiTailSpectralAlgebra.lean'
    dest.write_text('\n'.join(out))
    report = base/'results/multitail_extension/spectral_generation.json'
    report.parent.mkdir(parents=True,exist_ok=True)
    report.write_text(json.dumps(dict(certificates=meta, output_sha256=hashlib.sha256(dest.read_bytes()).hexdigest(),
                        scope='Algebra dictionary only; actual-integral bridge is separate.'),indent=2)+'\n')
    print(dest,meta)


if __name__ == '__main__':
    main()
