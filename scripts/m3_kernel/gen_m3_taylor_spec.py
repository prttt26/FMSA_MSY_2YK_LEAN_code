"""Generate MSAConvergence/M3TaylorSpec.lean from the literal `polynomial` in M3ResidualModel.lean.

Each polynomial term `C (coef) * X(some i)^a * ... * X none ^ b` becomes one spec entry
(exponents, coupling power, coefficient Expr). The coefficient Expr has six inputs:
pi, pi^-1, exp(-7), exp(-14), exp(-21), exp(-28). The generated Lean file proves that the spec
polynomial equals `polynomial i`, so this parser is not trusted.

Usage: python3 scripts/m3_kernel/gen_m3_taylor_spec.py
"""
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
src = (ROOT / 'MSAConvergence/M3ResidualModel.lean').read_text()
body = src.split('def polynomial : Fin 4 → MvPolynomial (Option (Fin 4)) ℝ :=\n  ![', 1)[1]
body = body.split('\n\nset_option', 1)[0].rstrip()
assert body.endswith(']')
rows = [r.strip() for r in body[:-1].split(',\n')]
assert len(rows) == 4
INPUT = {'(Real.pi ^ 1)⁻¹': 1, 'Real.pi': 0, '(Real.exp (-7 : ℝ))': 2, '(Real.exp (-14 : ℝ))': 3,
         '(Real.exp (-21 : ℝ))': 4, '(Real.exp (-28 : ℝ))': 5}

def split_top(s, sep):
    out, depth, cur = [], 0, ''
    i = 0
    while i < len(s):
        c = s[i]
        if c == '(': depth += 1
        elif c == ')': depth -= 1
        if depth == 0 and s.startswith(sep, i):
            out.append(cur); cur = ''; i += len(sep); continue
        cur += c; i += 1
    out.append(cur)
    return [x.strip() for x in out]

def strip(s):
    s = s.strip()
    while s.startswith('(') and s.endswith(')'):
        depth = 0
        for i, c in enumerate(s):
            depth += c == '('; depth -= c == ')'
            if depth == 0 and i < len(s) - 1: return s
        s = s[1:-1].strip()
    return s

def coef_expr(c):
    terms = split_top(strip(c), ' + ')
    exprs = []
    for t in terms:
        factors = split_top(strip(t), ' * ')
        m = re.fullmatch(r'\(\((-?\d+) : ℝ\)/(\d+)\)|\((-?\d+) : ℝ\)/(\d+)', factors[0])
        assert m, factors[0]
        p, q = (m.group(1), m.group(2)) if m.group(1) else (m.group(3), m.group(4))
        e = f'(.rational ({p}) {q})'
        for f in factors[1:]:
            assert f in INPUT, f
            e = f'(.mul {e} (.input {INPUT[f]}))'
        exprs.append(e)
    out = exprs[0]
    for e in exprs[1:]:
        out = f'(.add {out} {e})'
    return out

specs = []
for r in rows:
    entries = []
    for term in split_top(strip(r), ' + '):
        factors = split_top(strip(term), ' * ')
        assert factors[0].startswith('MvPolynomial.C '), factors[0]
        coef = factors[0][len('MvPolynomial.C '):]
        exps, tau = [0, 0, 0, 0], 0
        for f in factors[1:]:
            m = re.fullmatch(r'\(MvPolynomial\.X \(some \((\d) : Fin 4\)\)\) \^ (\d+)', f)
            if m: exps[int(m.group(1))] += int(m.group(2)); continue
            m = re.fullmatch(r'\(MvPolynomial\.X none\) \^ (\d+)', f)
            assert m, f
            tau += int(m.group(1))
        entries.append(f'([{", ".join(map(str, exps))}], {tau}, {coef_expr(coef)})')
    specs.append(entries)

lines = ',\n    '.join('[' + ',\n      '.join(e) + ']' for e in specs)
out = f'''import MSAConvergence.ComplexTaylorSpecs
import MSAConvergence.M3ResidualModel
import MSAConvergence.M3IntegerPhysicalInputs

/-! The literal M3 residual polynomials as coupling-affine specs.

Generated by `scripts/m3_kernel/gen_m3_taylor_spec.py` from `M3ResidualModel.polynomial`. The
generator is not trusted: `polynomial_eq_spec` proves that the spec polynomial equals the
literal one, and `spec_rel` proves that the interval coefficients enclose the real ones. -/
noncomputable section
namespace FMSA.Convergence.M3TaylorSpec
open ScaledIntegerIntervals ComplexTaylorSpecs

/-- The scale of the 128-bit integer grid. -/
def S : ℤ := 2 ^ 128

theorem S_pos : 0 < S := by unfold S; positivity

/-- Coefficient inputs: pi, pi⁻¹, exp(-7), exp(-14), exp(-21), exp(-28). -/
def physVals : Fin 6 → ℝ :=
  ![Real.pi, (Real.pi ^ 1)⁻¹, Real.exp (-7 : ℝ), Real.exp (-14 : ℝ), Real.exp (-21 : ℝ), Real.exp (-28 : ℝ)]

def physBounds : Fin 6 → Interval :=
  ![⟨1069028584064966747858780876442842309226, 1069028584064966747862183700112051693862⟩,
    ⟨108315241484954818046648587420924854560, 108315241484954818046993365542815312259⟩,
    ⟨310297353591408453456666808794198138, 310297353591408453463829122653711733⟩,
    ⟨282954560699298259517370576822755, 282954560699298259530432946503019⟩,
    ⟨258021160973090761041186135444, 258021160973090761059053144453⟩,
    ⟨235284843422800231064605145, 235284843422800231086328617⟩]

theorem phys_enclosed (i : Fin 6) : Encloses S (physBounds i) (physVals i) := by
  fin_cases i
  · simpa [physVals, physBounds, S] using M3IntegerPhysicalInputs.pi_input_enclosed
  · simpa [physVals, physBounds, S] using M3IntegerPhysicalInputs.pi_inverse_input_enclosed
  · simpa [physVals, physBounds, S] using M3IntegerPhysicalInputs.exp7_input_enclosed
  · simpa [physVals, physBounds, S] using M3IntegerPhysicalInputs.exp14_input_enclosed
  · simpa [physVals, physBounds, S] using M3IntegerPhysicalInputs.exp21_input_enclosed
  · simpa [physVals, physBounds, S] using M3IntegerPhysicalInputs.exp28_input_enclosed

def specE : List (List (List ℕ × ℕ × Expr 6)) := [
    {lines}]

def lR (k : ℕ) : SpecR := (specE.getD k []).map fun t => (t.1, t.2.1, Expr.eval physVals t.2.2)
def lI (k : ℕ) : SpecI := (specE.getD k []).map fun t => (t.1, t.2.1, Expr.enclose S physBounds t.2.2)

theorem spec_rel (k : ℕ) : SpecRel S (lI k) (lR k) := by
  unfold SpecRel lI lR
  induction specE.getD k [] with
  | nil => exact List.Forall₂.nil
  | cons t l ih =>
    exact List.Forall₂.cons ⟨rfl, rfl, Expr.enclose_sound S S_pos physVals physBounds phys_enclosed t.2.2⟩ ih

set_option maxHeartbeats 20000000 in
-- Literal expansion of four generated polynomials and exact ring normalization.
theorem polynomial_eq_spec (i : Fin 4) : M3ResidualModel.polynomial i = specPoly (lR i) := by
  apply MvPolynomial.funext
  intro v
  fin_cases i <;>
    simp [M3ResidualModel.polynomial, specPoly, lR, specE, monoPoly, varP, Expr.eval, physVals] <;>
    ring

end FMSA.Convergence.M3TaylorSpec
'''
(ROOT / 'MSAConvergence/M3TaylorSpec.lean').write_text(out)
print([len(e) for e in specs])
